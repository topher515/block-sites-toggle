#!/usr/bin/env node
// Builds the unpacked extension into build/:
//   - copies src/ (skipping modules/_*)
//   - generates defaults.js from config.json (+ sync.local.json if present)
//   - generates modules/registry.js from src/modules/*/index.js
const fs = require('fs');
const path = require('path');

const root = __dirname;
const srcDir = path.join(root, 'src');
const buildDir = path.join(root, 'build');

function readJson(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function copyDir(from, to, skip = () => false) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const s = path.join(from, entry.name);
    const d = path.join(to, entry.name);
    if (skip(s, entry) || entry.name === '.DS_Store' || entry.name.endsWith('.md') || (from === srcDir && entry.name === 'package.json')) continue;
    if (entry.isDirectory()) copyDir(s, d, skip);
    else fs.copyFileSync(s, d);
  }
}

function moduleDirs() {
  return fs
    .readdirSync(path.join(srcDir, 'modules'), { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('_'))
    .filter((e) => fs.existsSync(path.join(srcDir, 'modules', e.name, 'index.js')))
    .map((e) => e.name)
    .sort();
}

function generateRegistry(dirs) {
  const imports = dirs.map((d, i) => `import m${i} from './${d}/index.js';`).join('\n');
  const entries = dirs.map((d, i) => `  { dir: '${d}', exports: m${i} },`).join('\n');
  return `// Generated by build.js. Do not edit.\n${imports}\n\nexport default [\n${entries}\n];\n`;
}

function generateDefaults(config, sync) {
  const defaults = {
    mode: config.defaultMode || 'focus',
    sections: config.sections,
    sync: sync ? { url: sync.url || '', token: sync.token || '' } : { url: '', token: '' },
  };
  return `// Generated by build.js from config.json${sync ? ' and sync.local.json' : ''}. Do not edit.\nexport default ${JSON.stringify(defaults, null, 2)};\n`;
}

function build(configPath) {
  const config = readJson(configPath);
  const syncPath = path.join(root, 'sync.local.json');
  const sync = fs.existsSync(syncPath) ? readJson(syncPath) : null;

  fs.rmSync(buildDir, { recursive: true, force: true });
  copyDir(srcDir, buildDir, (s, e) => e.isDirectory() && e.name.startsWith('_') && path.dirname(s).endsWith('modules'));

  const dirs = moduleDirs();
  fs.writeFileSync(path.join(buildDir, 'modules', 'registry.js'), generateRegistry(dirs));
  fs.writeFileSync(path.join(buildDir, 'defaults.js'), generateDefaults(config, sync));

  const manifest = readJson(path.join(srcDir, 'manifest.json'));
  for (const k of ['name', 'version', 'description']) if (config[k]) manifest[k] = config[k];
  fs.writeFileSync(path.join(buildDir, 'manifest.json'), JSON.stringify(manifest, null, 2));

  return { dirs, sync: !!sync };
}

if (require.main === module) {
  const configPath = process.argv[2] || path.join(root, 'config.json');
  const { dirs, sync } = build(configPath);
  console.log(`Built ./build with modes from: ${dirs.join(', ')}${sync ? ' (sync preconfigured from sync.local.json)' : ''}`);
}

module.exports = { build };
